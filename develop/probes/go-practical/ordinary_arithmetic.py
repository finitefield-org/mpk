def nrec(base,step,n):return call('Std.Nat.rec',base,step,n)
def nstep(body):return lam('_index',nat(),lam('_accumulator',nat(),body))


class Arithmetic:
    def __init__(self):
        self.lib=Library();boolean_library(self.lib);boolean_theorems(self.lib)
    def emit(self,name,args,result,body,kind='definition'):self.lib.emit(N+name,args,result,body,kind)
    def theorem(self,name,args,e):self.emit(name,args,eq(e.ty,e.left,e.right),e.proof,'theorem')
    def definitions(self):
        a,b=var('a'),var('b');ab=[('a',nat()),('b',nat())]
        self.emit('Pred',[('a',nat())],nat(),nrec(zero(),lam('_index',nat(),lam('_accumulator',nat(),var('_index'))),a))
        self.emit('Add',ab,nat(),nrec(a,nstep(succ(var('_accumulator'))),b))
        self.emit('Mul',ab,nat(),nrec(zero(),nstep(add(var('_accumulator'),a)),b))
        self.emit('Sub',ab,nat(),nrec(a,nstep(nc('Pred',var('_accumulator'))),b))
        fn=pi('_argument',nat(),boolean())
        is_zero=induct('_n',boolean(),bit(True),lam('_n',nat(),lam('_ignored',boolean(),bit(False))),a)
        self.emit('IsZero',[('a',nat())],boolean(),is_zero)
        eq_base=lam('_other',nat(),nc('IsZero',var('_other')))
        eq_inner=induct('_m',boolean(),bit(False),lam('_m',nat(),lam('_ignored',boolean(),app(var('_prior'),var('_m')))),var('_other'))
        eq_step=lam('_n',nat(),lam('_prior',fn,lam('_other',nat(),eq_inner)))
        self.emit('Equal',ab,boolean(),app(induct('_n',fn,eq_base,eq_step,a),b))
        less_inner=induct('_m',boolean(),bit(True),lam('_m',nat(),lam('_ignored',boolean(),app(var('_prior'),var('_m')))),var('_other'))
        less_step=lam('_n',nat(),lam('_prior',fn,lam('_other',nat(),less_inner)))
        self.emit('Less',ab,boolean(),app(induct('_n',fn,lam('_other',nat(),bit(False)),less_step,b),a))
        self.emit('LessEqual',ab,boolean(),bc('Not',nc('Less',b,a)))
    def addition(self):
        a,b,c=var('a'),var('b'),var('c');ab=[('a',nat()),('b',nat())]
        self.theorem('AddZero',[('a',nat())],Equality(add(a,zero()),a,refl(nat(),a)))
        self.theorem('AddSucc',ab,Equality(add(a,succ(b)),succ(add(a,b)),refl(nat(),succ(add(a,b)))))
        self.theorem('PredZero',[],Equality(nc('Pred',zero()),zero(),refl(nat(),zero())))
        self.theorem('PredSucc',[('a',nat())],Equality(nc('Pred',succ(a)),a,refl(nat(),a)))
        # Zero + b = b by genuine unbounded Nat induction.
        n,ih=var('_n'),var('_ih');property_=eq(nat(),add(zero(),n),n)
        step=lam('_n',nat(),lam('_ih',property_,on_succ(Equality(add(zero(),n),n,ih)).proof))
        proof=induct('_n',property_,refl(nat(),zero()),step,b)
        self.theorem('ZeroAdd',[('b',nat())],Equality(add(zero(),b),b,proof))
        property_=eq(nat(),add(succ(a),n),succ(add(a,n)))
        step=lam('_n',nat(),lam('_ih',property_,on_succ(Equality(add(succ(a),n),succ(add(a,n)),ih)).proof))
        self.theorem('SuccAdd',ab,Equality(add(succ(a),b),succ(add(a,b)),induct('_n',property_,refl(nat(),succ(a)),step,b)))
        # Associativity: computation equations are explicit around the IH.
        left=add(add(a,b),n);right=add(a,add(b,n));property_=eq(nat(),left,right)
        e=add_succ(add(a,b),n).then(on_succ(Equality(left,right,ih)))
        e=e.then(add_succ(a,add(b,n)).reverse()).then(on_right(a,add_succ(b,n).reverse()))
        step=lam('_n',nat(),lam('_ih',property_,e.proof))
        base=add_zero(add(a,b)).then(on_right(a,add_zero(b)).reverse())
        self.theorem('AddAssoc',ab+[('c',nat())],Equality(add(add(a,b),c),add(a,add(b,c)),induct('_n',property_,base.proof,step,c)))
        property_=eq(nat(),add(a,n),add(n,a))
        step_e=add_succ(a,n).then(on_succ(Equality(add(a,n),add(n,a),ih))).then(succ_add(n,a).reverse())
        step=lam('_n',nat(),lam('_ih',property_,step_e.proof))
        base=add_zero(a).then(zero_add(a).reverse())
        self.theorem('AddComm',ab,Equality(add(a,b),add(b,a),induct('_n',property_,base.proof,step,b)))
        self.theorem('AddOne',[('a',nat())],Equality(add(a,one()),succ(a),refl(nat(),succ(a))))
    def multiplication(self):
        a,b,c=var('a'),var('b'),var('c');n,ih=var('_n'),var('_ih');ab=[('a',nat()),('b',nat())]
        mz=lambda x:lemma('MulZero',[x],mul(x,zero()),zero())
        zm=lambda x:lemma('ZeroMul',[x],mul(zero(),x),zero())
        ms=lambda x,y:lemma('MulSucc',[x,y],mul(x,succ(y)),add(mul(x,y),x))
        self.theorem('MulZero',[('a',nat())],Equality(mul(a,zero()),zero(),refl(nat(),zero())))
        self.theorem('MulSucc',ab,Equality(mul(a,succ(b)),add(mul(a,b),a),refl(nat(),add(mul(a,b),a))))
        property_=eq(nat(),mul(zero(),n),zero())
        e=ms(zero(),n).then(add_zero(mul(zero(),n))).then(Equality(mul(zero(),n),zero(),ih))
        self.theorem('ZeroMul',[('b',nat())],Equality(mul(zero(),b),zero(),induct('_n',property_,refl(nat(),zero()),lam('_n',nat(),lam('_ih',property_,e.proof)),b)))
        property_=eq(nat(),mul(one(),n),n)
        e=ms(one(),n).then(on_left(Equality(mul(one(),n),n,ih),one())).then(lemma('AddOne',[n],add(n,one()),succ(n)))
        self.theorem('OneMul',[('b',nat())],Equality(mul(one(),b),b,induct('_n',property_,refl(nat(),zero()),lam('_n',nat(),lam('_ih',property_,e.proof)),b)))
        e=ms(a,zero()).then(on_left(mz(a),a)).then(zero_add(a))
        self.theorem('MulOne',[('a',nat())],e)
        # Right distributivity by induction on c.
        left=mul(a,add(b,n));right=add(mul(a,b),mul(a,n));property_=eq(nat(),left,right)
        e=add_succ(b,n).mapped(lam('_sum',nat(),mul(a,var('_sum'))),mul(a,add(b,succ(n))),mul(a,succ(add(b,n))))
        e=e.then(ms(a,add(b,n))).then(on_left(Equality(left,right,ih),a)).then(assoc(mul(a,b),mul(a,n),a))
        e=e.then(on_right(mul(a,b),ms(a,n).reverse()))
        base=add_zero(b).mapped(lam('_sum',nat(),mul(a,var('_sum'))),mul(a,add(b,zero())),mul(a,b))
        base=base.then(add_zero(mul(a,b)).reverse()).then(on_right(mul(a,b),mz(a).reverse()))
        self.theorem('MulAddRight',ab+[('c',nat())],Equality(mul(a,add(b,c)),add(mul(a,b),mul(a,c)),induct('_n',property_,base.proof,lam('_n',nat(),lam('_ih',property_,e.proof)),c)))
        # Left distributivity needs only proved additive AC,not multiplication commutativity.
        left=mul(add(a,b),n);right=add(mul(a,n),mul(b,n));property_=eq(nat(),left,right)
        e=ms(add(a,b),n).then(on_left(Equality(left,right,ih),add(a,b)))
        reordered=add(add(mul(a,n),a),add(mul(b,n),b));e=e.then(AddNormalizer().prove(e.right,reordered))
        e=e.then(on_left(ms(a,n).reverse(),add(mul(b,n),b))).then(on_right(mul(a,succ(n)),ms(b,n).reverse()))
        base=mz(add(a,b)).then(reflexive(zero()))
        target=add(mul(a,zero()),mul(b,zero()))
        tail=on_left(mz(a),mul(b,zero())).then(on_right(zero(),mz(b))).then(add_zero(zero()))
        base=base.then(tail.reverse())
        self.theorem('MulAddLeft',ab+[('c',nat())],Equality(mul(add(a,b),c),add(mul(a,c),mul(b,c)),induct('_n',property_,base.proof,lam('_n',nat(),lam('_ih',property_,e.proof)),c)))
        # (succ a)*b = a*b+b follows from distributivity and1*b=b.
        e=lemma('AddOne',[a],add(a,one()),succ(a)).reverse().mapped(lam('_sum',nat(),mul(var('_sum'),b)),mul(succ(a),b),mul(add(a,one()),b))
        e=e.then(lemma('MulAddLeft',[a,one(),b],mul(add(a,one()),b),add(mul(a,b),mul(one(),b))))
        e=e.then(on_right(mul(a,b),lemma('OneMul',[b],mul(one(),b),b)))
        self.theorem('SuccMul',ab,e)
        property_=eq(nat(),mul(a,n),mul(n,a))
        e=ms(a,n).then(on_left(Equality(mul(a,n),mul(n,a),ih),a)).then(lemma('SuccMul',[n,a],mul(succ(n),a),add(mul(n,a),a)).reverse())
        base=mz(a).then(zm(a).reverse())
        self.theorem('MulComm',ab,Equality(mul(a,b),mul(b,a),induct('_n',property_,base.proof,lam('_n',nat(),lam('_ih',property_,e.proof)),b)))
        left=mul(mul(a,b),n);right=mul(a,mul(b,n));property_=eq(nat(),left,right)
        e=ms(mul(a,b),n).then(on_left(Equality(left,right,ih),mul(a,b)))
        distributed=lemma('MulAddRight',[a,mul(b,n),b],mul(a,add(mul(b,n),b)),add(mul(a,mul(b,n)),mul(a,b)))
        e=e.then(distributed.reverse()).then(ms(b,n).reverse().mapped(lam('_product',nat(),mul(a,var('_product'))),mul(a,add(mul(b,n),b)),mul(a,mul(b,succ(n)))))
        base=mz(mul(a,b)).then(mz(a).reverse()).then(mz(b).reverse().mapped(lam('_product',nat(),mul(a,var('_product'))),mul(a,zero()),mul(a,mul(b,zero()))))
        self.theorem('MulAssoc',ab+[('c',nat())],Equality(mul(mul(a,b),c),mul(a,mul(b,c)),induct('_n',property_,base.proof,lam('_n',nat(),lam('_ih',property_,e.proof)),c)))
    def equality_order(self):
        a,b,c=var('a'),var('b'),var('c');n,ih=var('_n'),var('_ih');ab=[('a',nat()),('b',nat())]
        bool_eq=lambda x,y,p:Equality(x,y,p,boolean())
        def computation(name,args,left,right):self.theorem(name,args,bool_eq(left,right,refl(boolean(),right)))
        computation('EqualZeroZero',[],nc('Equal',zero(),zero()),bit(True))
        computation('EqualZeroSucc',[('b',nat())],nc('Equal',zero(),succ(b)),bit(False))
        computation('EqualSuccZero',[('a',nat())],nc('Equal',succ(a),zero()),bit(False))
        computation('EqualSuccBoth',ab,nc('Equal',succ(a),succ(b)),nc('Equal',a,b))
        computation('LessZero',[('a',nat())],nc('Less',a,zero()),bit(False))
        computation('LessZeroSucc',[('b',nat())],nc('Less',zero(),succ(b)),bit(True))
        computation('LessSuccBoth',ab,nc('Less',succ(a),succ(b)),nc('Less',a,b))
        # Cancellation only uses successor injectivity derived with ordinary Pred.
        premise=lambda k:eq(nat(),add(a,k),add(b,k))
        prop=pi('_h',premise(n),eq(nat(),a,b))
        e=add_succ(a,n).reverse().then(Equality(add(a,succ(n)),add(b,succ(n)),var('_h'))).then(add_succ(b,n))
        pred=e.mapped(const(N+'Pred'),nc('Pred',e.left),nc('Pred',e.right))
        pa=lemma('PredSucc',[add(a,n)],nc('Pred',succ(add(a,n))),add(a,n));pb=lemma('PredSucc',[add(b,n)],nc('Pred',succ(add(b,n))),add(b,n))
        reduced=pa.reverse().then(pred).then(pb)
        step=lam('_n',nat(),lam('_ih',prop,lam('_h',premise(succ(n)),app(ih,reduced.proof))))
        base=lam('_h',premise(zero()),var('_h'))
        proof=induct('_n',prop,base,step,c)
        self.emit('AddCancel',ab+[('c',nat())],pi('_h',premise(c),eq(nat(),a,b)),proof,'theorem')
        # Boolean equality is both complete and reflective for genuine Nat equality.
        prop=eq(boolean(),nc('Equal',n,n),bit(True))
        step_e=bool_eq(nc('Equal',succ(n),succ(n)),nc('Equal',n,n),nc('EqualSuccBoth',n,n)).then(bool_eq(nc('Equal',n,n),bit(True),ih))
        proof=induct('_n',prop,nc('EqualZeroZero'),lam('_n',nat(),lam('_ih',prop,step_e.proof)),a)
        self.theorem('EqualReflexive',[('a',nat())],bool_eq(nc('Equal',a,a),bit(True),proof))
        target=lambda t:eq(boolean(),nc('Equal',a,t),bit(True))
        proof=call('Std.Eq.rewrite',nat(),a,b,lam('_other',nat(),target(var('_other'))),var('_same'),nc('EqualReflexive',a))
        self.emit('EqualComplete',ab+[('_same',eq(nat(),a,b))],target(b),proof,'theorem')
        def result(x,y):return pi('_true',eq(boolean(),nc('Equal',x,y),bit(True)),eq(nat(),x,y))
        def false_elim(x,y):return call('Probe.GoPractical.NatTermination.FalseElim',eq(nat(),x,y),var('_true'))
        k=var('_k');m=var('_m');outer=var('_outer');prior=var('_prior')
        base=lam('_true',eq(boolean(),nc('Equal',zero(),zero()),bit(True)),refl(nat(),zero()))
        base_step=lam('_k',nat(),lam('_unused',result(zero(),k),lam('_true',eq(boolean(),nc('Equal',zero(),succ(k)),bit(True)),false_elim(zero(),succ(k)))))
        base_all=lam('_m',nat(),induct('_k',result(zero(),k),base,base_step,m))
        outer_prop=pi('_m',nat(),result(outer,m))
        succ_base=lam('_true',eq(boolean(),nc('Equal',succ(outer),zero()),bit(True)),false_elim(succ(outer),zero()))
        reflected=Equality(outer,k,app(prior,k,var('_true')))
        succ_step=lam('_k',nat(),lam('_unused',result(succ(outer),k),lam('_true',eq(boolean(),nc('Equal',succ(outer),succ(k)),bit(True)),on_succ(reflected).proof)))
        step=lam('_outer',nat(),lam('_prior',outer_prop,lam('_m',nat(),induct('_k',result(succ(outer),k),succ_base,succ_step,m))))
        proof=app(induct('_outer',outer_prop,base_all,step,a),b)
        self.emit('EqualReflect',ab,result(a,b),proof,'theorem')
        # Simultaneous translation preserves strict order.
        less=lambda x,y:nc('Less',x,y)
        prop=eq(boolean(),less(add(a,n),add(b,n)),less(a,b))
        def mapped_left(e,right):return e.mapped(lam('_value',nat(),less(var('_value'),right)),less(e.left,right),less(e.right,right),boolean())
        def mapped_right(left,e):return e.mapped(lam('_value',nat(),less(left,var('_value'))),less(left,e.left),less(left,e.right),boolean())
        base=mapped_left(add_zero(a),add(b,zero())).then(mapped_right(a,add_zero(b)))
        e=mapped_left(add_succ(a,n),add(b,succ(n))).then(mapped_right(succ(add(a,n)),add_succ(b,n)))
        e=e.then(bool_eq(less(succ(add(a,n)),succ(add(b,n))),less(add(a,n),add(b,n)),nc('LessSuccBoth',add(a,n),add(b,n))))
        e=e.then(bool_eq(less(add(a,n),add(b,n)),less(a,b),ih))
        proof=induct('_n',prop,base.proof,lam('_n',nat(),lam('_ih',prop,e.proof)),c)
        self.theorem('LessTranslate',ab+[('c',nat())],bool_eq(less(add(a,c),add(b,c)),less(a,b),proof))
        prop=eq(boolean(),less(n,n),bit(False))
        e=bool_eq(less(succ(n),succ(n)),less(n,n),nc('LessSuccBoth',n,n)).then(bool_eq(less(n,n),bit(False),ih))
        proof=induct('_n',prop,nc('LessZero',zero()),lam('_n',nat(),lam('_ih',prop,e.proof)),a)
        self.theorem('LessIrreflexive',[('a',nat())],bool_eq(less(a,a),bit(False),proof))
        same=lambda x,y:nc('Equal',x,y)
        prop=eq(boolean(),same(add(a,n),add(b,n)),same(a,b))
        def eq_left(e,right):return e.mapped(lam('_value',nat(),same(var('_value'),right)),same(e.left,right),same(e.right,right),boolean())
        def eq_right(left,e):return e.mapped(lam('_value',nat(),same(left,var('_value'))),same(left,e.left),same(left,e.right),boolean())
        base=eq_left(add_zero(a),add(b,zero())).then(eq_right(a,add_zero(b)))
        e=eq_left(add_succ(a,n),add(b,succ(n))).then(eq_right(succ(add(a,n)),add_succ(b,n)))
        e=e.then(bool_eq(same(succ(add(a,n)),succ(add(b,n))),same(add(a,n),add(b,n)),nc('EqualSuccBoth',add(a,n),add(b,n))))
        e=e.then(bool_eq(same(add(a,n),add(b,n)),same(a,b),ih))
        self.theorem('EqualTranslate',ab+[('c',nat())],bool_eq(same(add(a,c),add(b,c)),same(a,b),induct('_n',prop,base.proof,lam('_n',nat(),lam('_ih',prop,e.proof)),c)))
    def subtraction(self):
        a,b,c=var('a'),var('b'),var('c');n,ih=var('_n'),var('_ih');ab=[('a',nat()),('b',nat())]
        sub=lambda x,y:nc('Sub',x,y);pred=lambda x:nc('Pred',x)
        sz=lambda x:lemma('SubZero',[x],sub(x,zero()),x)
        ss=lambda x,y:lemma('SubSucc',[x,y],sub(x,succ(y)),pred(sub(x,y)))
        ps=lambda x:lemma('PredSucc',[x],pred(succ(x)),x)
        self.theorem('SubZero',[('a',nat())],Equality(sub(a,zero()),a,refl(nat(),a)))
        self.theorem('SubSucc',ab,Equality(sub(a,succ(b)),pred(sub(a,b)),refl(nat(),pred(sub(a,b)))))
        prop=eq(nat(),pred(sub(a,n)),sub(pred(a),n))
        base=sz(a).mapped(const(N+'Pred'),pred(sub(a,zero())),pred(a)).then(sz(pred(a)).reverse())
        e=ss(a,n).mapped(const(N+'Pred'),pred(sub(a,succ(n))),pred(pred(sub(a,n))))
        e=e.then(Equality(pred(sub(a,n)),sub(pred(a),n),ih).mapped(const(N+'Pred'),pred(pred(sub(a,n))),pred(sub(pred(a),n))))
        e=e.then(ss(pred(a),n).reverse())
        self.theorem('PredSub',ab,Equality(pred(sub(a,b)),sub(pred(a),b),induct('_n',prop,base.proof,lam('_n',nat(),lam('_ih',prop,e.proof)),b)))
        e=ss(succ(a),b).then(lemma('PredSub',[succ(a),b],pred(sub(succ(a),b)),sub(pred(succ(a)),b)))
        e=e.then(ps(a).mapped(lam('_value',nat(),sub(var('_value'),b)),sub(pred(succ(a)),b),sub(a,b)))
        self.theorem('SubSuccBoth',ab,e)
        both=lambda x,y:lemma('SubSuccBoth',[x,y],sub(succ(x),succ(y)),sub(x,y))
        prop=eq(nat(),sub(zero(),n),zero())
        e=ss(zero(),n).then(Equality(sub(zero(),n),zero(),ih).mapped(const(N+'Pred'),pred(sub(zero(),n)),pred(zero())))
        e=e.then(lemma('PredZero',[],pred(zero()),zero()))
        self.theorem('ZeroSub',[('b',nat())],Equality(sub(zero(),b),zero(),induct('_n',prop,refl(nat(),zero()),lam('_n',nat(),lam('_ih',prop,e.proof)),b)))
        prop=eq(nat(),sub(n,n),zero());e=both(n,n).then(Equality(sub(n,n),zero(),ih))
        self.theorem('SubSame',[('a',nat())],Equality(sub(a,a),zero(),induct('_n',prop,refl(nat(),zero()),lam('_n',nat(),lam('_ih',prop,e.proof)),a)))
        prop=eq(nat(),sub(add(a,n),n),a)
        base=sz(add(a,zero())).then(add_zero(a))
        e=add_succ(a,n).mapped(lam('_value',nat(),sub(var('_value'),succ(n))),sub(add(a,succ(n)),succ(n)),sub(succ(add(a,n)),succ(n)))
        e=e.then(both(add(a,n),n)).then(Equality(sub(add(a,n),n),a,ih))
        self.theorem('SubAddRight',ab,Equality(sub(add(a,b),b),a,induct('_n',prop,base.proof,lam('_n',nat(),lam('_ih',prop,e.proof)),b)))
        prop=eq(nat(),sub(add(a,n),add(b,n)),sub(a,b))
        base=add_zero(a).mapped(lam('_value',nat(),sub(var('_value'),add(b,zero()))),sub(add(a,zero()),add(b,zero())),sub(a,add(b,zero())))
        base=base.then(add_zero(b).mapped(lam('_value',nat(),sub(a,var('_value'))),sub(a,add(b,zero())),sub(a,b)))
        e=add_succ(a,n).mapped(lam('_value',nat(),sub(var('_value'),add(b,succ(n)))),sub(add(a,succ(n)),add(b,succ(n))),sub(succ(add(a,n)),add(b,succ(n))))
        e=e.then(add_succ(b,n).mapped(lam('_value',nat(),sub(succ(add(a,n)),var('_value'))),sub(succ(add(a,n)),add(b,succ(n))),sub(succ(add(a,n)),succ(add(b,n)))))
        e=e.then(both(add(a,n),add(b,n))).then(Equality(sub(add(a,n),add(b,n)),sub(a,b),ih))
        self.theorem('SubTranslate',ab+[('c',nat())],Equality(sub(add(a,c),add(b,c)),sub(a,b),induct('_n',prop,base.proof,lam('_n',nat(),lam('_ih',prop,e.proof)),c)))
        prop=eq(nat(),sub(a,add(a,n)),zero())
        e=add_succ(a,n).mapped(lam('_value',nat(),sub(a,var('_value'))),sub(a,add(a,succ(n))),sub(a,succ(add(a,n))))
        e=e.then(ss(a,add(a,n))).then(Equality(sub(a,add(a,n)),zero(),ih).mapped(const(N+'Pred'),pred(sub(a,add(a,n))),pred(zero())))
        e=e.then(lemma('PredZero',[],pred(zero()),zero()))
        base=add_zero(a).mapped(lam('_value',nat(),sub(a,var('_value'))),sub(a,add(a,zero())),sub(a,a)).then(lemma('SubSame',[a],sub(a,a),zero()))
        self.theorem('SubExtra',ab,Equality(sub(a,add(a,b)),zero(),induct('_n',prop,base.proof,lam('_n',nat(),lam('_ih',prop,e.proof)),b)))
        # If a is not below b,then a=b+(a-b). This also proves the empty-range guard.
        outer,m,k=var('_outer'),var('_m'),var('_k')
        def result(x,y):return pi('_not_less',eq(boolean(),nc('Less',x,y),bit(False)),eq(nat(),add(y,sub(x,y)),x))
        def base_zero(x):
            e=sz(x).mapped(lam('_value',nat(),add(zero(),var('_value'))),add(zero(),sub(x,zero())),add(zero(),x)).then(zero_add(x))
