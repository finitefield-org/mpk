def release_fixture():
    value = {'schema': 'mpk.go_practical.release_linkage_fixture.v0', 'complete_bundle_registry': False, 'scope': 'immutable private external reference for source-artifact linkage; no release or tool provenance acceptance'}
    return {'value': value, 'reference': {'schema': SHARED['bundle_registry'][0], 'id': SHARED['release_registry'][0], 'registry_sha256': digest(SHARED['bundle_registry'][1], value)}}

def inventory(captured):
    rows = [{'kind': r['kind'], 'normalized_path': r['normalized_path'], 'size_bytes': len(bytes.fromhex(r['raw_hex'])), 'sha256': sha(bytes.fromhex(r['raw_hex']))} for r in captured]
    return sorted(rows, key=lambda r: (r['normalized_path'].encode(), r['kind'].encode()))

def scalar_entries(vir, path, size):
    rows = []
    for u in vir['program']['units']:
        for f in u['functions']:
            base = {'unit_id': u['id'], 'function_id': f['id']}
            refs = [{'kind': 'function', **base}]
            for b in f['blocks']:
                refs += [{'kind': 'instruction', **base, 'block': b['label'], 'instruction': op['id']} for op in b['instructions']]
                refs.append({'kind': 'terminator', **base, 'block': b['label']})
            rows += [{'reference': r, 'origin': {'kind': 'source', 'input_kind': 'source', 'normalized_path': path, 'start': 0, 'end': size}} for r in refs]

    def key(e):
        r = e['reference']
        return (r['unit_id'], r['function_id'], {'function': 0, 'instruction': 1, 'terminator': 2}[r['kind']], int(r.get('block', 'bb0')[2:]), int(r.get('instruction', 't0')[1:]))
    return sorted(rows, key=key)

def retained_data(row):
    name = row['id']
    vir = row['module']
    kind = vir['program']['kind']
    folder = RUST_DIR if name.startswith('rust') else GO_DIR
    m = json.loads((folder / 'source-manifest.frontend.json').read_bytes())
    payload = {k: copy.deepcopy(v) for k, v in m.items() if k not in OMIT}
    payload['kind'] = kind
    root = RUST_ROOT if name.startswith('rust') else GO_ROOT
    captured = []
    for i in payload['inputs']:
        p = root / i['normalized_path']
        raw = p.read_bytes() if p.is_file() else GENERATED[i['normalized_path']]
        captured.append({'kind': i['kind'], 'normalized_path': i['normalized_path'], 'raw_hex': raw.hex()})
    for observed, wanted in zip(inventory(captured), payload['inputs']):
        assert observed == wanted
    entries = json.loads((folder / 'source-map.json').read_bytes())['entries']
    if name == 'rust32':
        payload['target'] = {'id': 'i686-unknown-linux-gnu', 'pointer_width': 32}
    expected = copy.deepcopy(payload['release_registry'])
    payload['release_registry'] = release_fixture()['reference']
    authority = {'captured_inputs': captured, 'synthetic_permissions': [], 'expected_release_registry': expected, 'release_registry': release_fixture()['reference']}
    return (payload, entries, authority)

def bases():
    out = []
    for b in vir_bases():
        row = copy.deepcopy(b)
        vir = row['module']
        if 'project_spec' in row:
            p = Project(row['project_spec'])
            baseline = json.loads((GO_DIR / 'source-manifest.frontend.json').read_bytes())
            provenance = {k: copy.deepcopy(baseline[k]) for k in PROVENANCE}
            provenance['release_registry'] = release_fixture()['reference']
            row['authority'] = {'release_registry': release_fixture()['reference'], 'provenance': provenance}
            map_ = go_map(vir, p)
            payload = go_manifest(p, provenance)
        else:
            payload, entries, authority = retained_data(row)
            row['authority'] = authority
            map_ = source_map(vir, {'kind': vir['program']['kind'], 'entries': entries})
        row['source_map'] = map_
        row['manifest'] = frontend_manifest(vir, map_, payload)
        out.append(row)
    special = copy.deepcopy(out[0])
    special['id'] = 'go_fixed_synthetic'
    entry = next((e for e in special['source_map']['map']['entries'] if e['reference']['kind'] == 'instruction'))
    entry['origin'] = {'kind': 'synthetic', 'reason': 'profile.private.test'}
    special['authority']['synthetic_permissions'] = [{'reference': entry['reference'], 'reason': 'profile.private.test'}]
    special['source_map'] = source_map(special['module'], special['source_map']['map'])
    special['manifest'] = frontend_manifest(special['module'], special['source_map'], special['manifest']['manifest'])
    out.append(special)
    return out

def specs():
    rows = []
    for base in ('go_fixed', 'rust64', 'rust32', 'go-two-overlays', 'go-default-contracts'):
        for stage in ('map', 'manifest'):
            for name in ('same', 'extra-root', 'old-schema', 'wrong-profile-contract', 'wrong-context', 'wrong-vir', 'bad-hash', 'wrong-kind'):
                rows.append({'id': base + '-' + stage + '-' + name, 'base': base, 'stage': stage, 'mutation': name, 'expected_accepted': name == 'same'})
        for name in ('missing-reference', 'duplicate-reference', 'reference-order', 'wrong-origin'):
            rows.append({'id': base + '-map-' + name, 'base': base, 'stage': 'map', 'mutation': name, 'expected_accepted': False})
        names = ('inventory-sha', 'missing-input', 'selection', 'build-config', 'capture', 'release-ref') if base.startswith('go-') else ('input-sha', 'input-size', 'missing-input', 'selection', 'target', 'release-ref')
