def reseal(value, stage):
    field = 'source_map_hash' if stage == 'map' else 'source_manifest_hash'
    key = 'source_map' if stage == 'map' else 'frontend_manifest'
    value[field] = digest(SHARED[key][1], {k: v for k, v in value.items() if k != field})
    return value

def altered(spec, base):
    stage = spec['stage']
    value = copy.deepcopy(base['source_map' if stage == 'map' else 'manifest'])
    kind = spec['mutation']
    field = 'map' if stage == 'map' else 'manifest'
    payload = value[field]
    if kind == 'same':
        return value
    if kind == 'extra-root':
        value['caller_verified'] = True
    elif kind == 'old-schema':
        value['schema'] = 'mpk.source_map.v1' if stage == 'map' else 'mpk.source_manifest.v1'
    elif kind == 'wrong-profile-contract':
        value['profile_contract'] = 'mpk.profile.vir.go_fixed.v2'
    elif kind == 'wrong-context':
        value['semantic_context']['source_language'] = 'unknown'
    elif kind == 'wrong-vir':
        value['source_ir_hash' if stage == 'map' else 'vir_hash'] = '0' * 64
    elif kind == 'bad-hash':
        value['source_map_hash' if stage == 'map' else 'source_manifest_hash'] = '0' * 64
        return value
    elif kind == 'wrong-kind':
        payload['kind'] = 'caller_extension'
    elif stage == 'map':
        entries = payload['entries']
        if kind == 'missing-reference':
            entries.pop()
        elif kind == 'duplicate-reference':
            entries.append(copy.deepcopy(entries[0]))
        elif kind == 'reference-order':
            entries.reverse()
        elif kind == 'split-utf8':
            entries[0]['origin']['start'] = 4
        elif kind == 'wrong-reason':
            next((e for e in entries if e['origin']['kind'] == 'synthetic'))['origin']['reason'] = 'caller.permission'
        elif kind == 'wrong-origin':
            origin = entries[0]['origin']
            origin['end_byte' if 'end_byte' in origin else 'end'] = 999999
        else:
            raise AssertionError(kind)
    elif payload['kind'] == 'go_practical':
        if kind == 'inventory-sha':
            payload['input_inventory']['objects'][0]['raw_sha256'] = '0' * 64
        elif kind == 'missing-input':
            payload['input_inventory']['objects'].pop()
        elif kind == 'selection':
            payload['selection']['value']['roots'] = []
        elif kind == 'build-config':
            payload['build_config']['goarch'] = 'arm64'
        elif kind == 'capture':
            payload['capture_context']['objects'] = []
        elif kind == 'release-ref':
            payload['release_registry']['registry_sha256'] = '0' * 64
        else:
            raise AssertionError(kind)
    elif kind == 'input-sha':
        payload['inputs'][0]['sha256'] = '0' * 64
    elif kind == 'input-size':
        payload['inputs'][0]['size_bytes'] += 1
    elif kind == 'missing-input':
        payload['inputs'].pop()
    elif kind == 'selection':
        payload['selection']['value']['caller_flag'] = True
    elif kind == 'target':
        payload['target']['id'] = 'wrong-target'
    elif kind == 'release-ref':
        payload['release_registry']['registry_sha256'] = '0' * 64
    else:
        raise AssertionError(kind)
    if stage == 'manifest':
        if payload['kind'] == 'go_practical':
            if kind in {'inventory-sha', 'missing-input'}:
                inv = payload['input_inventory']
                if kind == 'inventory-sha':
                    n = inv['objects'][0]
                    n['id'] = digest(IDENTITY_SHAPES['source_object'][1], {k: v for k, v in n.items() if k != 'id'})
                    inv['objects'].sort(key=lambda x: x['id'])
                inv['content_sha256'] = digest(INVENTORY_DOMAIN, {k: v for k, v in inv.items() if k != 'content_sha256'})
            elif kind in {'capture', 'build-config'}:
                n = payload['capture_context' if kind == 'capture' else 'build_config']
                family = 'capture_context' if kind == 'capture' else 'build_config'
                n['id'] = digest(IDENTITY_SHAPES[family][1], {k: v for k, v in n.items() if k != 'id'})
        elif kind in {'input-sha', 'input-size', 'missing-input'}:
            payload['input_set_hash'] = digest('MPK-INPUT-SET-0.1', payload['inputs'])
    return reseal(value, stage)

def queries(data, rows):
    by_id = {b['id']: b for b in data}
    out = {}
    for row in rows:
        b = by_id[row['base']]
        if 'project_spec' in b:
            continue
        changed = altered(row, b)
        a = Artifacts(None, None, b['authority'])
        try:
            q = a.query(b['module'], changed if row['stage'] == 'map' else b['source_map'], changed if row['stage'] == 'manifest' else None)
        except ValueError:
            continue
        out[canonical(q)] = q
    return [out[k] for k in sorted(out)]
