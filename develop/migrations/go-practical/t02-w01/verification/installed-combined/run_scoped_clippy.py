"""Check only the real test-configured observer, with a lint control."""
from pathlib import Path
import json
import os
import subprocess
import sys
import tarfile
import time

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[5]
CARGO = Path('/private/tmp/mpk-go-source-root-matching/cargo')
TARGET = Path('/private/tmp/mpk-go-source-root-matching/target')
REGISTRY = Path('/Users/kazuyoshitoshiya/.cargo/registry')
IMAGE = 'sha256:7cf1e580ef5539f03b58560753e8ab84c8c360960d99dff714004aa98f203977'
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT.parent / 'installed-compiler'))
from run_scoped import seal, sdk_files, write


def main():
    epoch = sys.argv[1]
    assert epoch.replace('-', '').isalnum() and Path.cwd() == REPO
    prior_root = ROOT / 'scope-original'
    prior = json.loads((prior_root / 'result.json').read_bytes())
    inputs = json.loads((prior_root / 'inputs.json').read_bytes())
    assert prior['status'] == 'failed' and prior['original_inputs_unchanged']
    changed = [row['path'] for row in inputs['inputs'] if seal(Path(row['path'])) != row]
    assert changed == [str(REPO / 'crates/mpk-cli/examples/go_practical_live_combined_roots.rs')]
    wrapper = ROOT / 'scoped_clippy_wrapper.py'
    driver = subprocess.run(['rustup', 'which', 'clippy-driver'], cwd=REPO, capture_output=True, text=True, check=False)
    assert driver.returncode == 0 and not driver.stderr and Path(driver.stdout.strip()).is_absolute()
    out = ROOT / epoch
    out.mkdir(exist_ok=False)
    fixture = out / 'lint-control'
    (fixture / 'examples').mkdir(parents=True)
    (fixture / 'Cargo.toml').write_text('[package]\nname = "mpk-scoped-clippy-control"\nversion = "0.0.0"\nedition = "2021"\n\n[workspace]\n')
    (fixture / 'Cargo.lock').write_text('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "mpk-scoped-clippy-control"\nversion = "0.0.0"\n')
    (fixture / 'examples/go_practical_live_combined_roots.rs').write_text('fn main() { let selected = std::env::args().len() > 1; if selected == true { eprintln!("control"); } }\n')
    paths = {Path(row['path']) for row in inputs['inputs']}
    paths.update([Path(__file__).resolve(), wrapper])
    paths.update(path for path in fixture.rglob('*') if path.is_file())
    source = [seal(path) for path in sorted(paths)]
    sdk = sdk_files()
    with tarfile.open(out / 'inputs.tar.gz', 'x:gz', dereference=True) as archive:
        for path in sorted(paths):
            archive.add(path, arcname=str(path.relative_to(REPO)), recursive=False)
    common = {'CARGO_NET_OFFLINE': 'true', 'CARGO_INCREMENTAL': '0', 'CARGO_PROFILE_DEV_DEBUG': '0'}
    scoped = {**common, 'RUSTC_WORKSPACE_WRAPPER': str(wrapper), 'MPK_SCOPED_CLIPPY_DRIVER': driver.stdout.strip()}
    host_normal = {**common, 'CARGO_TARGET_DIR': '/private/tmp/mpk-go-source-root-clippy-target'}
    control_env = {**scoped, 'CARGO_TARGET_DIR': '/private/tmp/mpk-scoped-clippy-control-target', 'MPK_SCOPED_CLIPPY_LOG': str(out / 'lint-control.target.jsonl')}
    target_env = {**scoped, 'CARGO_TARGET_DIR': '/private/tmp/mpk-scoped-clippy-original-target', 'MPK_SCOPED_CLIPPY_LOG': str(out / 'lint-original.target.jsonl')}
    rust_env = {'CARGO_HOME': '/cargo', 'CARGO_TARGET_DIR': '/target', 'CARGO_NET_OFFLINE': 'true', 'CARGO_INCREMENTAL': '0', 'CARGO_PROFILE_DEV_DEBUG': '0', 'HOME': '/tmp'}
    rust = ['/usr/local/bin/docker', 'run', '--pull=never', '--rm', '--platform', 'linux/arm64', '--network', 'none', '--read-only', '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges', '--user', f'{os.getuid()}:{os.getgid()}', '--tmpfs', '/tmp:rw,exec,nosuid,nodev,size=1g,mode=1777', '--mount', f'type=bind,src={REPO},dst=/workspace,readonly', '--mount', f'type=bind,src={CARGO},dst=/cargo', '--mount', f'type=bind,src={REGISTRY},dst=/cargo/registry,readonly', '--mount', f'type=bind,src={TARGET},dst=/target', '--workdir', '/workspace']
    for key, value in rust_env.items():
        rust += ['--env', f'{key}={value}']
    commands = {
        'lint-control': ['cargo', 'check', '--offline', '--locked', '--manifest-path', str(fixture / 'Cargo.toml'), '--example', 'go_practical_live_combined_roots', '--target', 'x86_64-unknown-linux-gnu'],
        'clippy-normal': ['cargo', 'clippy', '--offline', '--locked', '-p', 'mpk-cli', '--example', 'go_practical_live_combined_roots', '--target', 'x86_64-unknown-linux-gnu', '--', '-D', 'warnings'],
        'rust-format': ['rustfmt', '--edition', '2021', '--check', '--config', 'skip_children=true', str(REPO / 'crates/mpk-cli/examples/go_practical_live_combined_roots.rs')],
        'lint-original': ['cargo', 'check', '--offline', '--locked', '-p', 'mpk-cli', '--example', 'go_practical_live_combined_roots', '--target', 'x86_64-unknown-linux-gnu'],
        'test-observer-build': rust + [IMAGE, 'cargo', 'rustc', '--offline', '--locked', '-p', 'mpk-cli', '--example', 'go_practical_live_combined_roots', '--', '--cfg', 'test', '-Aexplicit_builtin_cfgs_in_flags', '-Dwarnings'],
    }
    envs = {'lint-control': control_env, 'clippy-normal': host_normal, 'lint-original': target_env}
    write(out / 'inputs.json', {'selection_reason': 'Apply the actual Clippy driver and test cfg only to the selected observer via a forwarding wrapper. A separate deliberate lint error confirms the driver is active; no original source or dependency is replaced.', 'inputs': source, 'archive': seal(out / 'inputs.tar.gz'), 'registered_sdk': sdk, 'previous_inputs': seal(prior_root / 'inputs.json'), 'previous_result': seal(prior_root / 'result.json'), 'previous_archive': inputs['archive'], 'changed_previous_inputs': changed, 'commands': commands, 'environments': envs, 'rust_environment': rust_env, 'clippy_driver': driver.stdout.strip()})
    result = {'status': 'running', 'native_Linux_release_acceptance': False, 'full_T_gate': 'Deferred to final T02-W04: ./scripts/check-fast.sh'}
    write(out / 'result.json', result)
    checks = {}
    started = time.monotonic()
    for name, command in commands.items():
        actual_env = {key: value for key, value in os.environ.items() if key not in ('RUSTC_WRAPPER', 'RUSTC_WORKSPACE_WRAPPER', 'RUSTFLAGS', 'CARGO_ENCODED_RUSTFLAGS')}
        actual_env.update(envs.get(name, {}))
        with (out / (name + '.stdout')).open('xb') as stdout, (out / (name + '.stderr')).open('xb') as stderr:
            code = subprocess.run(command, cwd=REPO, env=actual_env, stdout=stdout, stderr=stderr, check=False).returncode
        stderr_text = (out / (name + '.stderr')).read_text()
        okay = code != 0 and 'clippy::bool_comparison' in stderr_text if name == 'lint-control' else code == 0
        if name in ('lint-control', 'lint-original'):
            log = out / (name + '.target.jsonl')
            okay = okay and log.is_file() and len(log.read_text().splitlines()) >= 1
        checks[name] = {'status': 'passed' if okay else 'failed', 'exit_code': code, 'stdout': seal(out / (name + '.stdout')), 'stderr': seal(out / (name + '.stderr'))}
        if name in ('lint-control', 'lint-original') and (out / (name + '.target.jsonl')).is_file():
            checks[name]['target_invocations'] = seal(out / (name + '.target.jsonl'))
        print(json.dumps({'check': name, 'status': checks[name]['status'], 'seconds': round(time.monotonic() - started)}), flush=True)
    unchanged = source == [seal(path) for path in sorted(paths)] and sdk == sdk_files()
    passed = unchanged and all(item['status'] == 'passed' for item in checks.values())
    result.update(status='passed' if passed else 'failed', seconds=time.monotonic() - started, original_inputs_unchanged=unchanged, checks=checks)
    write(out / 'result.json', result)
    print(json.dumps({'status': result['status'], 'original_inputs_unchanged': unchanged}), flush=True)
    raise SystemExit(not passed)


if __name__ == '__main__':
    main()
