#[test]
fn v2_routes_and_transports_are_closed_against_both_generations() {
    let active_vectors = load("develop/specs/vectors/ai-api-v1.json");
    assert_eq!(active_vectors["api_profile"], AI_API_V1_PROFILE);
    let vector_routes = active_vectors["route_registry"]
        .as_array()
        .expect("AI API v1 route vectors");
    assert_eq!(SUCCESSOR_ROUTES.len(), V1_ROUTES.len());
    assert_eq!(SUCCESSOR_ROUTES.len(), vector_routes.len());
    for ((successor, active), vector) in SUCCESSOR_ROUTES.iter().zip(V1_ROUTES).zip(vector_routes) {
        assert_eq!(successor.method, active.method);
        assert_eq!(successor.path, active.path);
        assert_eq!(successor.handler, active.handler);
        assert_eq!(vector["method"], active.method);
        assert_eq!(vector["path"], active.path);
        assert_eq!(vector["handler"], active.handler.as_str());
        assert_eq!(
            resolve_route(SUCCESSOR_AI_API_PROFILE, successor.method, successor.path)
                .expect("successor route resolves"),
            successor.handler
        );
        assert_eq!(
            resolve_route(active.method, active.path).expect("active route still resolves"),
            active.handler
        );
    }
    let error = resolve_route(AI_API_V1_PROFILE, "POST", "/vir/import")
        .expect_err("old API profile rejects at the successor router");
    assert_error(
        error,
        SuccessorValidationPhase::Route,
        SuccessorApiErrorCode::ApiProfile,
    );
    let error = resolve_route(SUCCESSOR_AI_API_PROFILE, "POST", "/v2/vir/import")
        .expect_err("route aliases reject");
    assert_error(
        error,
        SuccessorValidationPhase::Route,
        SuccessorApiErrorCode::RouteUnknown,
    );

    let registry = registry();
    let csharp = csharp_source(&registry);
    let store = store(&registry, std::slice::from_ref(&csharp));
    let mut service = SuccessorApiService::new(registry, store).expect("service builds");
    let old_start = canonical_transport(&json!({
        "module_name":"Example.Api.Old",
        "proof_profile":"mvp-strict"
    }));
    let error = service
        .handle_start_session(&old_start)
        .expect_err("v1 session shape rejects in v2");
    assert_error(
        error,
        SuccessorValidationPhase::Shape,
        SuccessorApiErrorCode::Shape,
    );
    assert_eq!(service.mutation_count(), 0);

    let mut successor_start = start_request(&csharp, "Example.Api.Successor");
    let successor_transport = canonical_transport(&successor_start);
    let error = parse_v1_request::<StartSessionRequest>(&successor_transport, 1_048_576)
        .err()
        .expect("v2 session shape rejects in v1");
    assert_eq!(error.code, V1ErrorCode::Shape);
    successor_start["api_profile"] = json!(AI_API_V1_PROFILE);
    let error = service
        .handle_start_session(&canonical_transport(&successor_start))
        .expect_err("old discriminator rejects");
    assert_error(
        error,
        SuccessorValidationPhase::Route,
        SuccessorApiErrorCode::ApiProfile,
    );
    assert_eq!(service.mutation_count(), 0);

    assert_vector_ownership();
}

#[test]
fn all_three_profiles_produce_deterministic_bound_successor_sessions_and_vcs() {
    let registry = registry();
    let profiles = profiles(&registry);
    let store = store(
        &registry,
        &[
            profiles.go.clone(),
            profiles.rust.clone(),
            profiles.csharp.clone(),
        ],
    );

    for (name, source) in [
        ("Go", &profiles.go),
        ("Rust", &profiles.rust),
        ("CSharp", &profiles.csharp),
    ] {
        let first = run_profile(&registry, &store, source, name);
        let second = run_profile(&registry, &store, source, name);
        assert_eq!(first, second, "{name} API bytes are deterministic");
        for response in &first {
            assert!(response.ends_with(b"\n"));
            let value = response_value(response);
            assert_eq!(value["api_profile"], SUCCESSOR_AI_API_PROFILE);
            assert_eq!(value["helper_only"], true);
            assert!(value.get("accepted").is_none());
            assert!(value.get("mpk_verified").is_none());
            assert!(value.get("proof_evidence").is_none());
        }
        let generated = response_value(&first[2]);
        assert_eq!(generated["source_ir_schema"], "mpk.vir.v1");
        assert_eq!(
            generated["source_manifest_schema"],
            "mpk.source_manifest.v1"
        );
        assert_eq!(generated["source_vc_schema"], "mpk.vc.v2");
        assert_eq!(
            generated["semantic_context"]["source_language"],
            source.vir.module().semantic_context().source_language()
        );
        assert_eq!(
            generated["selection"],
            serde_json::to_value(source.manifest.manifest().selection())
                .expect("selection serializes")
        );
    }
}

#[test]
fn crossed_old_stale_and_noncanonical_operations_reject_atomically() {
    let registry = registry();
    let profiles = profiles(&registry);
    let store = store(
        &registry,
        &[
            profiles.go.clone(),
            profiles.rust.clone(),
            profiles.csharp.clone(),
        ],
    );
    let mut service = SuccessorApiService::new(registry, store).expect("service builds");

    let mut unknown = import_request("s404", &profiles.go);
    unknown["semantic_context"] = json!({});
    let error = service
        .handle_vir_import(&canonical_transport(&unknown))
        .expect_err("unknown session precedes context validation");
    assert_eq!(error.code, SuccessorApiErrorCode::UnknownSession);
    assert_eq!(service.mutation_count(), 0);

    let go_start = response_value(
        &service
            .handle_start_session(&canonical_transport(&start_request(
                &profiles.go,
                "Example.Api.Go",
            )))
            .expect("Go session starts"),
    );
    let rust_start = response_value(
        &service
            .handle_start_session(&canonical_transport(&start_request(
                &profiles.rust,
                "Example.Api.Rust",
            )))
            .expect("Rust session starts"),
    );
    assert_eq!(go_start["session_id"], "s1");
    assert_eq!(rust_start["session_id"], "s2");

    let before = fingerprint(&service, &["s1", "s2"]);
    let mut crossed_identity = import_request("s1", &profiles.rust);
    crossed_identity["session_id"] = json!("s1");
    let error = service
        .handle_vir_import(&canonical_transport(&crossed_identity))
        .expect_err("cross-profile session identity rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::ContextMismatch);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before);

    let mut crossed_selection = import_request("s1", &profiles.go);
    crossed_selection["selection"] =
        serde_json::to_value(profiles.rust.manifest.manifest().selection())
            .expect("Rust selection serializes");
    let error = service
        .handle_vir_import(&canonical_transport(&crossed_selection))
        .expect_err("cross-profile selection rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::ContextMismatch);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before);

    let mut crossed_artifact = import_request("s1", &profiles.go);
    crossed_artifact["vir"] =
        serde_json::from_slice(profiles.rust.vir.canonical_bytes()).expect("Rust VIR JSON");
    crossed_artifact["source_ir_hash"] = json!(profiles.rust.vir.hash().as_str());
    let error = service
        .handle_vir_import(&canonical_transport(&crossed_artifact))
        .expect_err("crossed successor VIR rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::ContextMismatch);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before);

    let mut old = import_request("s1", &profiles.go);
    old["source_ir_schema"] = json!("mpk.vir.v0");
    let error = service
        .handle_vir_import(&canonical_transport(&old))
        .expect_err("old VIR discriminator rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::VirSchema);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before);

    let pretty = pretty_transport(&import_request("s2", &profiles.rust));
    let error = service
        .handle_vir_import(&pretty)
        .expect_err("noncanonical request rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::CanonicalTransport);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before);

    service
        .handle_vir_import(&canonical_transport(&import_request("s1", &profiles.go)))
        .expect("Go VIR imports");
    service
        .handle_vir_import(&canonical_transport(&import_request("s2", &profiles.rust)))
        .expect("Rust VIR imports");
    let before_generate = fingerprint(&service, &["s1", "s2"]);
    let mut crossed_manifest = generate_request("s1", &profiles.go);
    crossed_manifest["source_manifest_hash"] = json!(profiles.rust.manifest.hash().as_str());
    crossed_manifest["input_set_hash"] =
        json!(profiles.rust.manifest.manifest().input_set_hash().as_str());
    let error = service
        .handle_vc_generate(&canonical_transport(&crossed_manifest))
        .expect_err("crossed manifest capability rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::ContextMismatch);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before_generate);

    let generated = response_value(
        &service
            .handle_vc_generate(&canonical_transport(&generate_request("s1", &profiles.go)))
            .expect("Go VC generates"),
    );
    let context = vc_context(&generated);
    let before_context_failure = fingerprint(&service, &["s1", "s2"]);
    let mut stale = context.clone();
    stale["vc_hash"] = json!(ZERO_SHA256);
    let error = service
        .handle_vc_list(&canonical_transport(&stale))
        .expect_err("stale VC rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::ContextMismatch);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before_context_failure);

    let mut old_vc = context.clone();
    old_vc["source_vc_schema"] = json!("mpk.vc.v1");
    let error = service
        .handle_vc_list(&canonical_transport(&old_vc))
        .expect_err("old VC discriminator rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::ContextMismatch);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before_context_failure);

    let mut unknown_target = context;
    unknown_target["target"] = json!({"kind":"member","id":"missing"});
    let error = service
        .handle_vc_start_proof(&canonical_transport(&unknown_target))
        .expect_err("unknown target rejects");
    assert_eq!(error.code, SuccessorApiErrorCode::TargetUnknown);
    assert_eq!(fingerprint(&service, &["s1", "s2"]), before_context_failure);

    let mut active = V1ApiService::new(ValidatedFrontendArtifactStore::empty());
    active
        .start_session(StartSessionRequest::new("Example.Api.Active"))
        .expect("active session starts");
    let before_active = active.mutation_count();
    let error = active
        .handle_vir_import(&canonical_transport(&import_request("s1", &profiles.go)))
        .expect_err("successor request rejects at active boundary");
    assert_eq!(error.code, V1ErrorCode::Shape);
    assert_eq!(active.mutation_count(), before_active);
}

