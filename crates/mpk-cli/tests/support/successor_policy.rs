pub(super) fn generated_pair(
    registry: &ValidatedSemanticProfileRegistry,
    source: &ValidatedSource,
    vc_contract: &Value,
) -> GeneratedPair {
    let linked = SuccessorVcSource {
        registry,
        vir: &source.vir,
        manifest: &source.manifest,
        profile_contract: vc_contract,
    };
    let vc = generate_successor_vc(linked).expect("successor VC");
    let skeleton = emit_successor_vc_skeleton(&vc, linked).expect("successor skeleton");
    GeneratedPair { vc, skeleton }
}

pub(super) fn source_boundary<'a>(
    registry: &'a ValidatedSemanticProfileRegistry,
    source: &'a ValidatedSource,
    pair: &'a GeneratedPair,
    policy_contract: &'a Value,
    evidence_contract: &'a Value,
    captured: &'a [CapturedInput<'a>],
) -> SuccessorPolicySource<'a> {
    SuccessorPolicySource {
        registry,
        vir: &source.vir,
        source_map: &source.source_map,
        frontend_manifest: &source.manifest,
        vc: &pair.vc,
        skeleton: &pair.skeleton,
        policy_contract,
        evidence_contract,
        captured_inputs: captured,
    }
}

