fn input_kind(value: &Value) -> InputKind {
    match value.as_str().expect("input kind") {
        "source" => InputKind::Source,
        "contract" => InputKind::Contract,
        "build_manifest" => InputKind::BuildManifest,
        "lockfile" => InputKind::Lockfile,
        other => panic!("unknown input kind {other}"),
    }
}

fn captured_storage(source_root: &str, manifest: &Value) -> Vec<OwnedCapturedInput> {
    manifest["inputs"]
        .as_array()
        .expect("manifest inputs")
        .iter()
        .map(|entry| {
            let kind = input_kind(&entry["kind"]);
            let normalized_path = entry["normalized_path"]
                .as_str()
                .expect("normalized input path")
                .to_owned();
            let path = repository_root().join(source_root).join(&normalized_path);
            let bytes = match fs::read(&path) {
                Ok(bytes) => bytes,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => match kind {
                    InputKind::BuildManifest if normalized_path == "Cargo.toml" => {
                        GENERATED_CARGO_TOML.to_vec()
                    }
                    InputKind::Lockfile if normalized_path == "Cargo.lock" => {
                        GENERATED_CARGO_LOCK.to_vec()
                    }
                    InputKind::Lockfile if normalized_path == "go.sum" => Vec::new(),
                    _ => panic!("read captured input {}: {error}", path.display()),
                },
                Err(error) => panic!("read captured input {}: {error}", path.display()),
            };
            assert_eq!(entry["size_bytes"], bytes.len() as u64);
            assert_eq!(entry["sha256"], sha256_raw_file_bytes(&bytes).to_hex());
            OwnedCapturedInput {
                kind,
                normalized_path,
                bytes,
            }
        })
        .collect()
}

pub(super) fn captured_refs(storage: &[OwnedCapturedInput]) -> Vec<CapturedInput<'_>> {
    storage
        .iter()
        .map(|input| CapturedInput {
            kind: input.kind,
            normalized_path: &input.normalized_path,
            bytes: &input.bytes,
        })
        .collect()
}

pub(super) fn staged_source(
    registry: &ValidatedSemanticProfileRegistry,
    artifact_root: &str,
    source_root: &str,
) -> ValidatedSource {
    let vir_bytes = read(format!("{artifact_root}/vir.json"));
    let map_bytes = read(format!("{artifact_root}/source-map.json"));
    let manifest_bytes = read(format!("{artifact_root}/source-manifest.frontend.json"));
    let manifest_value: Value = serde_json::from_slice(&manifest_bytes).expect("manifest JSON");
    let map_value: Value = serde_json::from_slice(&map_bytes).expect("source-map JSON");
    let storage = captured_storage(source_root, &manifest_value);
    let captured = captured_refs(&storage);
    let vir = import_successor_vir_json(&vir_bytes, registry).expect("successor VIR");
    let synthetic_permissions = map_value["entries"]
        .as_array()
        .expect("source-map entries")
        .iter()
        .filter(|entry| entry["origin"]["kind"] == "synthetic")
        .map(|entry| {
            let reason = entry["origin"]["reason"]
                .as_str()
                .expect("synthetic reason");
            assert_eq!(reason, "go.control_flow_join");
            SyntheticPermission {
                reference: serde_json::from_value::<SourceReference>(entry["reference"].clone())
                    .expect("synthetic reference"),
                reason: reason.to_owned(),
            }
        })
        .collect::<Vec<_>>();
    let source_map = import_successor_source_map_json(
        &map_bytes,
        SuccessorSourceMapValidationContext {
            registry,
            vir: &vir,
            captured_inputs: &captured,
            synthetic_permissions: &synthetic_permissions,
        },
    )
    .expect("successor source map");
    let release_registry = serde_json::from_value::<ReleaseRegistryIdentity>(
        manifest_value["release_registry"].clone(),
    )
    .expect("release-registry identity");
    let manifest = import_successor_source_manifest_json(
        &manifest_bytes,
        SuccessorSourceManifestStage::Frontend,
        SuccessorSourceManifestValidationContext {
            registry,
            vir: &vir,
            source_map: &source_map,
            captured_inputs: &captured,
            expected_release_registry: &release_registry,
        },
    )
    .expect("successor source manifest");
    ValidatedSource {
        storage,
        vir,
        source_map,
        manifest,
    }
}

