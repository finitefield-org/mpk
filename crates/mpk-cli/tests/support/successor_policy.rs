pub(super) fn fixture(relative: &str, generated: &[u8]) {
    let path = repository_root().join(FIXTURE_ROOT).join(relative);
    if std::env::var_os(UPDATE_FIXTURES_ENV).as_deref() == Some(std::ffi::OsStr::new("1")) {
        fs::create_dir_all(path.parent().expect("fixture parent")).expect("create fixture parent");
        fs::write(&path, generated).expect("write fixture");
    }
    assert_eq!(
        fs::read(&path).unwrap_or_else(|error| panic!("read {}: {error}", path.display())),
        generated,
        "fixture drift: {}",
        path.display()
    );
}

pub(super) fn hex_fixture(bytes: &[u8]) -> Vec<u8> {
    let mut encoded = String::with_capacity(bytes.len() * 2 + 1);
    for byte in bytes {
        use std::fmt::Write;
        write!(&mut encoded, "{byte:02x}").expect("write to String");
    }
    encoded.push('\n');
    encoded.into_bytes()
}

