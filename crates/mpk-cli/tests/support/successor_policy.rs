fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("repository root")
}

fn read(relative: impl AsRef<Path>) -> Vec<u8> {
    fs::read(repository_root().join(relative.as_ref()))
        .unwrap_or_else(|error| panic!("read {}: {error}", relative.as_ref().display()))
}

pub(super) fn load(relative: impl AsRef<Path>) -> Value {
    serde_json::from_slice(&read(relative)).expect("checked-in JSON")
}

pub(super) fn canonical(value: &Value) -> Vec<u8> {
    let encoded = serde_json::to_vec(value).expect("JSON serializes");
    let strict = parse_strict_json(
        &encoded,
        StrictJsonLimits::new(268_435_456, 268_435_456, 768, 1_048_576),
    )
    .expect("strict JSON");
    canonical_json_bytes(&strict).expect("canonical JSON")
}

pub(super) fn registry() -> ValidatedSemanticProfileRegistry {
    validate_semantic_profile_registry(
        &read("release/bundles/semantic-profile-registry.json"),
        RegistryRevision::Revision4,
    )
    .expect("revision-4 semantic registry")
}

pub(super) fn candidate_registry() -> ValidatedSemanticProfileRegistry {
    let vector = load("develop/specs/vectors/semantic-profile-registry-v4.json");
    validate_semantic_profile_registry(
        &canonical_registry_transport(&vector["registry"])
            .expect("canonical revision-4 semantic registry"),
        RegistryRevision::Revision4,
    )
    .expect("revision-4 semantic registry vector")
}

fn input_kind(value: &Value) -> InputKind {
    match value.as_str().expect("input kind") {
        "source" => InputKind::Source,
        "contract" => InputKind::Contract,
        "build_manifest" => InputKind::BuildManifest,
        "lockfile" => InputKind::Lockfile,
        other => panic!("unknown input kind {other}"),
    }
}

fn captured_storage(source_root: &str, manifest: &Value) -> Vec<OwnedCapturedInput> {
    manifest["inputs"]
        .as_array()
        .expect("manifest inputs")
        .iter()
        .map(|entry| {
            let kind = input_kind(&entry["kind"]);
            let normalized_path = entry["normalized_path"]
                .as_str()
                .expect("normalized input path")
                .to_owned();
            let path = repository_root().join(source_root).join(&normalized_path);
            let bytes = match fs::read(&path) {
                Ok(bytes) => bytes,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => match kind {
                    InputKind::BuildManifest if normalized_path == "Cargo.toml" => {
                        GENERATED_CARGO_TOML.to_vec()
                    }
                    InputKind::Lockfile if normalized_path == "Cargo.lock" => {
                        GENERATED_CARGO_LOCK.to_vec()
                    }
                    InputKind::Lockfile if normalized_path == "go.sum" => Vec::new(),
                    _ => panic!("read captured input {}: {error}", path.display()),
                },
                Err(error) => panic!("read captured input {}: {error}", path.display()),
            };
            assert_eq!(entry["size_bytes"], bytes.len() as u64);
            assert_eq!(entry["sha256"], sha256_raw_file_bytes(&bytes).to_hex());
            OwnedCapturedInput {
                kind,
                normalized_path,
                bytes,
            }
        })
        .collect()
}

pub(super) fn captured_refs(storage: &[OwnedCapturedInput]) -> Vec<CapturedInput<'_>> {
    storage
        .iter()
        .map(|input| CapturedInput {
            kind: input.kind,
            normalized_path: &input.normalized_path,
            bytes: &input.bytes,
        })
        .collect()
}

pub(super) fn staged_source(
    registry: &ValidatedSemanticProfileRegistry,
    artifact_root: &str,
    source_root: &str,
) -> ValidatedSource {
    let vir_bytes = read(format!("{artifact_root}/vir.json"));
    let map_bytes = read(format!("{artifact_root}/source-map.json"));
    let manifest_bytes = read(format!("{artifact_root}/source-manifest.frontend.json"));
    let manifest_value: Value = serde_json::from_slice(&manifest_bytes).expect("manifest JSON");
    let map_value: Value = serde_json::from_slice(&map_bytes).expect("source-map JSON");
    let storage = captured_storage(source_root, &manifest_value);
    let captured = captured_refs(&storage);
    let vir = import_successor_vir_json(&vir_bytes, registry).expect("successor VIR");
    let synthetic_permissions = map_value["entries"]
        .as_array()
        .expect("source-map entries")
        .iter()
        .filter(|entry| entry["origin"]["kind"] == "synthetic")
        .map(|entry| {
            let reason = entry["origin"]["reason"]
                .as_str()
                .expect("synthetic reason");
            assert_eq!(reason, "go.control_flow_join");
            SyntheticPermission {
                reference: serde_json::from_value::<SourceReference>(entry["reference"].clone())
                    .expect("synthetic reference"),
                reason: reason.to_owned(),
            }
        })
        .collect::<Vec<_>>();
    let source_map = import_successor_source_map_json(
        &map_bytes,
        SuccessorSourceMapValidationContext {
            registry,
            vir: &vir,
            captured_inputs: &captured,
            synthetic_permissions: &synthetic_permissions,
        },
    )
    .expect("successor source map");
    let release_registry = serde_json::from_value::<ReleaseRegistryIdentity>(
        manifest_value["release_registry"].clone(),
    )
    .expect("release-registry identity");
    let manifest = import_successor_source_manifest_json(
        &manifest_bytes,
        SuccessorSourceManifestStage::Frontend,
        SuccessorSourceManifestValidationContext {
            registry,
            vir: &vir,
            source_map: &source_map,
            captured_inputs: &captured,
            expected_release_registry: &release_registry,
        },
    )
    .expect("successor source manifest");
    ValidatedSource {
        storage,
        vir,
        source_map,
        manifest,
    }
}

pub(super) fn go_identity_source(registry: &ValidatedSemanticProfileRegistry) -> ValidatedSource {
    let baseline = load("fixtures/vir-go/frontend/basic-arith/source-manifest.frontend.json");
    let context = baseline["semantic_context"].clone();
    let package = "github.com/finitefield-org/mpk/fixtures/go-basic/positive/arith";
    let function = format!("{package}.Identity");
    let i64_type = json!({"kind":"bv","width":64,"signed":true});
    let mut contract = json!({
        "semantic_context":context.clone(),
        "unit_id":package,
        "function_id":function,
        "requires":[],
        "ensures":[{"lhs":{"result":0},"op":"eq","rhs":{"var":"arg0"}}],
        "modifies":[],
        "panic":"forbidden",
        "termination":"total",
        "loops":[],
        "contract_hash":ZERO_SHA256
    });
    contract["contract_hash"] = Value::String(
        successor_contract_hash_value(&contract)
            .expect("Go contract hash")
            .as_str()
            .to_owned(),
    );
    let mut vir = json!({
        "schema":"mpk.vir.v1",
        "semantic_context":context,
        "units":[{
            "id":package,
            "name":"arith",
            "type_decls":[],
            "const_decls":[],
            "functions":[{
                "id":function,
                "unit_id":package,
                "name":"Identity",
                "params":[{"id":"arg0","type":i64_type.clone()}],
                "results":[{"id":"result0","type":i64_type}],
                "locals":[],
                "blocks":[{
                    "label":"bb0",
                    "parameters":[],
                    "instructions":[],
                    "terminator":{"kind":"Return","values":[{"var":"arg0"}]}
                }],
                "contracts":contract,
                "features_used":[]
            }]
        }],
        "vir_hash":ZERO_SHA256
    });
    vir["vir_hash"] = Value::String(
        successor_vir_hash_value(&vir)
            .expect("Go VIR hash")
            .as_str()
            .to_owned(),
    );
    let vir = import_successor_vir_json(&canonical(&vir), registry).expect("Go successor VIR");

    let storage = vec![
        OwnedCapturedInput {
            kind: InputKind::BuildManifest,
            normalized_path: "go.mod".to_owned(),
            bytes: read("fixtures/go-basic/go.mod"),
        },
        OwnedCapturedInput {
            kind: InputKind::Lockfile,
            normalized_path: "go.sum".to_owned(),
            bytes: Vec::new(),
        },
        OwnedCapturedInput {
            kind: InputKind::Source,
            normalized_path: "positive/arith/arith.go".to_owned(),
            bytes: GO_SOURCE.to_vec(),
        },
    ];
    let captured = captured_refs(&storage);
    let origin = || {
        json!({
            "kind":"source",
            "input_kind":"source",
            "normalized_path":"positive/arith/arith.go",
            "start":0,
            "end":GO_SOURCE.len()
        })
    };
    let mut source_map = json!({
        "schema":"mpk.source_map.v1",
        "semantic_context":vir.module().semantic_context(),
        "source_ir_schema":"mpk.vir.v1",
        "source_ir_hash":vir.hash().as_str(),
        "entries":[{
            "reference":{"kind":"function","unit_id":package,"function_id":function},
            "origin":origin()
        },{
            "reference":{
                "kind":"terminator",
                "unit_id":package,
                "function_id":function,
                "block":"bb0"
            },
            "origin":origin()
        }],
        "source_map_hash":ZERO_SHA256
    });
    source_map["source_map_hash"] = Value::String(
        successor_source_map_hash_value(&source_map)
            .expect("Go source-map hash")
            .as_str()
            .to_owned(),
    );
    let source_map = import_successor_source_map_json(
        &canonical(&source_map),
        SuccessorSourceMapValidationContext {
            registry,
            vir: &vir,
            captured_inputs: &captured,
            synthetic_permissions: &[],
        },
    )
    .expect("Go successor source map");
    let inputs = storage
        .iter()
        .map(|input| InputEntry {
            kind: input.kind,
            normalized_path: input.normalized_path.clone(),
            size_bytes: input.bytes.len() as i64,
            sha256: sha256_raw_file_bytes(&input.bytes).to_hex(),
        })
        .collect::<Vec<_>>();
    let release_registry =
        serde_json::from_value::<ReleaseRegistryIdentity>(baseline["release_registry"].clone())
            .expect("Go release-registry identity");
    let mut manifest = baseline;
    manifest["selection"]["value"]["function"] = Value::String(function);
    manifest["inputs"] = serde_json::to_value(&inputs).expect("Go inputs");
    manifest["input_set_hash"] = Value::String(
        input_set_hash(&inputs)
            .expect("Go input-set hash")
            .as_str()
            .to_owned(),
    );
    manifest["vir_hash"] = Value::String(vir.hash().as_str().to_owned());
    manifest["source_map_hash"] = Value::String(source_map.hash().as_str().to_owned());
    manifest["source_manifest_hash"] = Value::String(ZERO_SHA256.to_owned());
    manifest["source_manifest_hash"] = Value::String(
        successor_source_manifest_hash_value(&manifest)
            .expect("Go source-manifest hash")
            .as_str()
            .to_owned(),
    );
    let manifest = import_successor_source_manifest_json(
        &canonical(&manifest),
        SuccessorSourceManifestStage::Frontend,
        SuccessorSourceManifestValidationContext {
            registry,
            vir: &vir,
            source_map: &source_map,
            captured_inputs: &captured,
            expected_release_registry: &release_registry,
        },
    )
    .expect("Go successor manifest");
    ValidatedSource {
        storage,
        vir,
        source_map,
        manifest,
    }
}

