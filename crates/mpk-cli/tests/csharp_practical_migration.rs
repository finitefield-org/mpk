fn active_context(profile: &str, parameters: &Value) -> Value {
    let registry = load(ACTIVE_REGISTRY_PATH);
    predecessor_context(&registry, profile, parameters)
}

fn predecessor_context(registry: &Value, profile: &str, parameters: &Value) -> Value {
    let entry = registry["profiles"]
        .as_array()
        .unwrap()
        .iter()
        .find(|entry| entry["semantic_profile"] == profile)
        .unwrap_or_else(|| panic!("missing active profile {profile}"));
    json!({
        "profile_registry": {
            "schema": registry["schema"],
            "id": registry["id"],
            "revision": registry["revision"],
            "registry_sha256": registry["registry_sha256"],
        },
        "profile_entry_sha256": entry["entry_sha256"],
        "source_language": entry["source_language"],
        "semantic_profile": entry["semantic_profile"],
        "semantic_parameters": parameters,
    })
}

fn scalar_baseline_storage(profile: &Value) -> Vec<OwnedCapturedInput> {
    profile["case_harness"]["baseline_files"]
        .as_object()
        .unwrap()
        .iter()
        .map(|(path, value)| {
            let (kind, bytes) = if path.ends_with(".json") {
                (InputKind::Contract, canonical_line(value))
            } else {
                (
                    InputKind::Source,
                    value.as_str().expect("baseline source").as_bytes().to_vec(),
                )
            };
            OwnedCapturedInput {
                kind,
                normalized_path: path.clone(),
                bytes,
            }
        })
        .collect()
}

fn csharp_message(status: &str, code: &str) -> &'static str {
    if code == "CSHARP_SOURCE_DIAGNOSTIC" {
        "C# compiler diagnostic CS0103"
    } else if code.starts_with("CSHARP_LIMIT_") {
        "C# profile limit exceeded"
    } else {
        match status {
            "source-error" => "C# source is invalid",
            "rejected" => "C# source is outside the frozen profile",
            "frontend-error" => "C# frontend failed closed",
            other => panic!("unexpected C# failure status {other}"),
        }
    }
}

fn java_message(status: &str, code: &str) -> &'static str {
    if code.starts_with("JAVA_LIMIT_") {
        "Java profile limit exceeded"
    } else {
        match status {
            "source-error" => "Java source is invalid",
            "rejected" => "Java source is outside the frozen profile",
            "frontend-error" => "Java frontend failed closed",
            other => panic!("unexpected Java failure status {other}"),
        }
    }
}

