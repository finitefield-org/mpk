fn validate_predecessor(
    registry: &ValidatedSemanticProfileRegistry,
    envelope: &Value,
    captured_inputs: &[CapturedInput<'_>],
    synthetic_permissions: &[SyntheticPermission],
) -> AcceptedSuccessorFrontendEnvelope {
    let context = validate_registry_semantic_context(registry, &envelope["semantic_context"])
        .expect("predecessor semantic context");
    let selection =
        validate_registry_selection_envelope(registry, &context, &envelope["selection"])
            .expect("predecessor selection");
    let release = envelope
        .get("source_manifest")
        .and_then(|manifest| manifest.get("release_registry"))
        .map(|value| serde_json::from_value(value.clone()).expect("release registry identity"))
        .unwrap_or_else(dummy_release);
    let stdout = canonical_line(envelope);
    validate_successor_frontend_process(
        SuccessorFrontendProtocolRequest {
            registry,
            semantic_context: &context,
            selection: &selection,
            release_registry: &release,
            captured_inputs,
            synthetic_permissions,
        },
        process(
            &stdout,
            exit_for_status(envelope["status"].as_str().expect("status")),
        ),
    )
    .expect("predecessor envelope validates")
}

fn input_kind(value: &Value) -> InputKind {
    match value.as_str().expect("input kind") {
        "source" => InputKind::Source,
        "contract" => InputKind::Contract,
        "build_manifest" => InputKind::BuildManifest,
        "lockfile" => InputKind::Lockfile,
        other => panic!("unknown input kind {other}"),
    }
}

fn captured_storage(source_root: &str, manifest: &Value) -> Vec<OwnedCapturedInput> {
    manifest["inputs"]
        .as_array()
        .expect("manifest inputs")
        .iter()
        .map(|entry| {
            let kind = input_kind(&entry["kind"]);
            let normalized_path = entry["normalized_path"]
                .as_str()
                .expect("normalized path")
                .to_owned();
            let path = repository_root().join(source_root).join(&normalized_path);
            let bytes = match fs::read(&path) {
                Ok(bytes) => bytes,
                Err(error)
                    if error.kind() == std::io::ErrorKind::NotFound
                        && kind == InputKind::BuildManifest
                        && normalized_path == "Cargo.toml" =>
                {
                    GENERATED_CARGO_TOML.to_vec()
                }
                Err(error)
                    if error.kind() == std::io::ErrorKind::NotFound
                        && kind == InputKind::Lockfile
                        && normalized_path == "Cargo.lock" =>
                {
                    GENERATED_CARGO_LOCK.to_vec()
                }
                Err(error)
                    if error.kind() == std::io::ErrorKind::NotFound
                        && kind == InputKind::Lockfile =>
                {
                    Vec::new()
                }
                Err(error) => panic!("read captured input {}: {error}", path.display()),
            };
            assert_eq!(bytes.len() as u64, entry["size_bytes"].as_u64().unwrap());
            assert_eq!(
                sha256_raw_file_bytes(&bytes).to_hex(),
                entry["sha256"].as_str().unwrap()
            );
            OwnedCapturedInput {
                kind,
                normalized_path,
                bytes,
            }
        })
        .collect()
}

