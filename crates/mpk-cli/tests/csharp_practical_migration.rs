struct DifferenceReportCase {
    report: &'static str,
    language: &'static str,
    profile: &'static str,
    accepted_source: &'static str,
    accepted_array: &'static str,
    accepted_count: u64,
    accepted_ids_sha256: &'static str,
    rejected_source: &'static str,
    rejected_array: &'static str,
    rejected_count: u64,
    rejected_ids_sha256: &'static str,
}

fn case_ids_sha256(source: &Value, field: &str) -> String {
    let ids = source[field]
        .as_array()
        .unwrap_or_else(|| panic!("{field} array"))
        .iter()
        .map(|case| case["id"].clone())
        .collect::<Vec<_>>();
    sha256_raw_file_bytes(&serde_json::to_vec(&ids).expect("case ID transport")).to_hex()
}

fn assert_test_owner_exists(owner: &str) {
    let (path, test) = owner.split_once('#').expect("path#test owner");
    let source = String::from_utf8(read(path)).expect("UTF-8 test owner");
    let test = if test.starts_with("CSHARP-") {
        test.to_ascii_lowercase().replace('-', "_")
    } else {
        test.to_owned()
    };
    assert!(
        source.contains(&format!("fn {test}")),
        "missing test owner {owner}"
    );
}

