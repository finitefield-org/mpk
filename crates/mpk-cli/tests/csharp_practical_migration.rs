fn replace_once(bytes: &[u8], from: &str, to: &str) -> Vec<u8> {
    let text = std::str::from_utf8(bytes).expect("UTF-8 transport");
    assert_eq!(
        text.matches(from).count(),
        1,
        "unique mutation target {from}"
    );
    text.replacen(from, to, 1).into_bytes()
}

