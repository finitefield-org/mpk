fn artifact<'a>(case: &'a Value, kind: &str) -> &'a Value {
    case["artifacts"]
        .as_array()
        .expect("artifact descriptors")
        .iter()
        .find(|artifact| artifact["kind"] == kind)
        .unwrap_or_else(|| panic!("missing {kind} for {}", case["id"]))
}

fn checked_artifact(root: &str, descriptor: &Value) -> Vec<u8> {
    let path = descriptor["path"].as_str().expect("artifact path");
    let bytes = read(Path::new(root).join(path));
    assert_eq!(bytes.len() as u64, descriptor["bytes"].as_u64().unwrap());
    assert_eq!(
        sha256_raw_file_bytes(&bytes).to_hex(),
        descriptor["sha256"].as_str().unwrap()
    );
    bytes
}

fn assert_final_hash(artifact: &PrivateSuccessorArtifact, hash_field: &str, domain: &'static str) {
    let hash = artifact.sha256();
    let suffix = format!(",\"{hash_field}\":\"{hash}\"}}");
    assert!(
        artifact.canonical_bytes().ends_with(suffix.as_bytes()),
        "{} must end in its hash field",
        artifact.schema()
    );
    let mut preimage =
        artifact.canonical_bytes()[..artifact.canonical_bytes().len() - suffix.len()].to_vec();
    preimage.push(b'}');
    assert_eq!(
        hash_domain_separated_raw(HashDomain::new(domain), &preimage)
            .expect("artifact hash")
            .to_hex(),
        hash,
        "{} hash",
        artifact.schema()
    );
}

fn contains_string(value: &Value, needle: &str) -> bool {
    match value {
        Value::String(value) => value == needle,
        Value::Array(values) => values.iter().any(|value| contains_string(value, needle)),
        Value::Object(values) => values.values().any(|value| contains_string(value, needle)),
        Value::Null | Value::Bool(_) | Value::Number(_) => false,
    }
}

fn assert_common_migration(migration: &PrivatePredecessorMigration, producer: PredecessorProducer) {
    assert_eq!(migration.producer(), producer);
    assert_eq!(
        migration.request().schema(),
        SUCCESSOR_FRONTEND_REQUEST_SCHEMA
    );
    assert_final_hash(
        migration.request(),
        "request_sha256",
        "MPK-FRONTEND-REQUEST-2.0",
    );
    let mut expected_stdout = migration.frontend_result().canonical_bytes().to_vec();
    expected_stdout.push(b'\n');
    assert_eq!(migration.frontend_stdout(), expected_stdout);
    assert_eq!(
        migration
            .frontend_stdout()
            .iter()
            .filter(|byte| **byte == b'\n')
            .count(),
        1
    );
    assert_eq!(migration.equivalence().axiom_count(), 0);
    assert_eq!(migration.equivalence().practical_foundation_instances(), 0);
    for digest in [
        migration.equivalence().source_behavior_sha256(),
        migration.equivalence().obligation_sha256(),
        migration.equivalence().verdict_sha256(),
    ] {
        assert_eq!(digest.len(), 64);
        assert!(digest
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)));
    }

    let request = parse_line(migration.request().canonical_bytes());
    assert_eq!(request["schema"], SUCCESSOR_FRONTEND_REQUEST_SCHEMA);
    assert_eq!(
        request["semantic_request"]["semantic_context"]["profile_registry"]["revision"],
        SUCCESSOR_CANDIDATE_REVISION
    );
    let result = parse_line(migration.frontend_result().canonical_bytes());
    for predecessor_schema in [
        "mpk.frontend.cli.v1",
        "mpk.vir.v1",
        "mpk.source_map.v1",
        "mpk.source_manifest.v1",
    ] {
        assert!(
            !contains_string(&result, predecessor_schema),
            "predecessor schema escaped: {predecessor_schema}"
        );
    }

    if let Some(artifacts) = migration.artifacts() {
        assert_eq!(
            migration.frontend_result().schema(),
            SUCCESSOR_FRONTEND_SUCCESS_SCHEMA
        );
        assert_eq!(result["request_sha256"], request["request_sha256"]);
        assert_eq!(
            result["semantic_context"],
            request["semantic_request"]["semantic_context"]
        );
        assert_eq!(
            result["artifacts"]["semantic_context"],
            result["semantic_context"]
        );
        assert!(schema_accepts(
            PrivateSuccessorSchemaKind::FrontendSourceArtifacts,
            &result["artifacts"],
        ));
        for (artifact, hash_field, domain, schema) in [
            (
                artifacts.vir(),
                "vir_sha256",
                "MPK-VIR-2.0",
                SUCCESSOR_VIR_SCHEMA,
            ),
            (
                artifacts.source_map(),
                "source_map_sha256",
                "MPK-SOURCE-MAP-2.0",
                SUCCESSOR_SOURCE_MAP_SCHEMA,
            ),
            (
                artifacts.source_manifest(),
                "manifest_sha256",
                "MPK-SOURCE-MANIFEST-2.0",
                SUCCESSOR_FRONTEND_MANIFEST_SCHEMA,
            ),
            (
                artifacts.semantic_bindings(),
                "binding_set_sha256",
                "MPK-CSHARP-SEMANTIC-BINDING-SET-1.0",
                SUCCESSOR_SEMANTIC_BINDINGS_SCHEMA,
            ),
            (
                artifacts.closed_instances(),
                "closed_set_sha256",
                "MPK-CSHARP-CLOSED-INSTANCES-1.0",
                SUCCESSOR_CLOSED_INSTANCES_SCHEMA,
            ),
            (
                artifacts.source_artifacts(),
                "artifacts_sha256",
                "MPK-FRONTEND-SOURCE-ARTIFACTS-2.0",
                SUCCESSOR_SOURCE_ARTIFACTS_SCHEMA,
            ),
        ] {
            assert_eq!(artifact.schema(), schema);
            assert_final_hash(artifact, hash_field, domain);
        }
        assert_final_hash(
            migration.frontend_result(),
            "success_sha256",
            "MPK-FRONTEND-SUCCESS-2.0",
        );
        let closed = parse_line(artifacts.closed_instances().canonical_bytes());
        assert_eq!(closed["instances"], json!([]));
        assert_eq!(closed["semantic_profile"], producer.semantic_profile());
    } else {
        assert_eq!(
            migration.frontend_result().schema(),
            SUCCESSOR_FRONTEND_DIAGNOSTIC_SCHEMA
        );
        assert_final_hash(
            migration.frontend_result(),
            "diagnostic_sha256",
            "MPK-FRONTEND-DIAGNOSTIC-2.0",
        );
        assert_eq!(result["status"], "rejected");
        assert!(result.get("artifacts").is_none());
        assert_eq!(result["request_linkage"]["state"], "validated");
        assert_eq!(
            result["request_linkage"]["request_sha256"],
            request["request_sha256"]
        );
        assert_eq!(
            result["raw_request_sha256"],
            sha256_raw_file_bytes(migration.request().canonical_bytes()).to_hex()
        );
        assert_eq!(
            result["raw_request_size_bytes"],
            migration.request().canonical_bytes().len() as u64
        );
    }
}

struct SyntheticFailure<'a> {
    status: &'a str,
    phase: &'a str,
    code: &'a str,
    message: &'a str,
}

fn synthetic_failure(
    registry: &ValidatedSemanticProfileRegistry,
    context: &Value,
    selection: &Value,
    failure: SyntheticFailure<'_>,
    captured: &[CapturedInput<'_>],
) -> AcceptedSuccessorFrontendEnvelope {
    let issue = json!({"code": failure.code, "message": failure.message});
    let rejected = failure.status == "rejected";
    let envelope = json!({
        "schema": "mpk.frontend.cli.v1",
        "status": failure.status,
        "phase": failure.phase,
        "semantic_context": context,
        "selection": selection,
        "rejected_features": if rejected { vec![issue.clone()] } else { Vec::new() },
        "diagnostics": if rejected { Vec::new() } else { vec![issue] },
    });
    validate_predecessor(registry, &envelope, captured, &[])
}

