fn generated_pair<'a>(
    registry: &'a ValidatedSemanticProfileRegistry,
    source: &'a ValidatedSource,
    contract: &'a Value,
) -> (
    mpk_vc::successor_vc::ValidatedSuccessorVc,
    mpk_vc::successor_vc::ValidatedSuccessorVcSkeleton,
) {
    let linked = SuccessorVcSource {
        registry,
        vir: &source.vir,
        manifest: &source.manifest,
        profile_contract: contract,
    };
    let first = generate_successor_vc(linked).expect("successor VC generation");
    let second = generate_successor_vc(linked).expect("repeat successor VC generation");
    assert_eq!(first.canonical_bytes(), second.canonical_bytes());
    assert_eq!(first.document().schema(), SUCCESSOR_VC_SCHEMA);
    assert_eq!(first.document().source_ir_schema(), "mpk.vir.v1");
    assert_eq!(
        first.document().source_manifest_schema(),
        "mpk.source_manifest.v1"
    );
    assert_eq!(first.hash(), first.document().vc_hash());
    assert!(!first.canonical_bytes().ends_with(b"\n"));
    assert!(serde_json::from_slice::<VcDocument>(first.canonical_bytes()).is_err());

    let skeleton = emit_successor_vc_skeleton(&first, linked).expect("successor skeleton");
    let repeated = emit_successor_vc_skeleton(&first, linked).expect("repeat skeleton");
    assert_eq!(skeleton.canonical_bytes(), repeated.canonical_bytes());
    assert_eq!(skeleton.skeleton().schema(), SUCCESSOR_VC_SKELETON_SCHEMA);
    assert_eq!(skeleton.skeleton().source_vc_hash(), first.hash());
    assert!(!skeleton.canonical_bytes().ends_with(b"\n"));
    assert!(serde_json::from_slice::<VcCertificateSkeletonV1>(skeleton.canonical_bytes()).is_err());
    (first, skeleton)
}

