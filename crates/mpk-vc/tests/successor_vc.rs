#[test]
fn csharp_required_checks_reach_the_checked_bool_bv_foundation() {
    let registry = registry();
    let csharp = csharp_source(&registry);
    let contract = profile_contract("csharp");
    let (vc, skeleton) = generated_pair(&registry, &csharp, &contract);
    let observed = vc
        .required_checks()
        .iter()
        .map(|audit| audit.check().clone())
        .collect::<Vec<_>>();
    let expected = vec![
        VirSafetyCheck::IntegerNoOverflow {
            operation: mpk_vc::OverflowOperation::Add,
            signed: true,
        },
        VirSafetyCheck::IntegerNoOverflow {
            operation: mpk_vc::OverflowOperation::Sub,
            signed: true,
        },
        VirSafetyCheck::IntegerNoOverflow {
            operation: mpk_vc::OverflowOperation::Mul,
            signed: true,
        },
        VirSafetyCheck::IntegerNoOverflow {
            operation: mpk_vc::OverflowOperation::Neg,
            signed: true,
        },
        VirSafetyCheck::DivisorNonzero {},
        VirSafetyCheck::SignedDivremRepresentable {
            operation: mpk_vc::DivRemOperation::Div,
        },
        VirSafetyCheck::DivisorNonzero {},
        VirSafetyCheck::SignedDivremRepresentable {
            operation: mpk_vc::DivRemOperation::Rem,
        },
        VirSafetyCheck::DivisorNonzero {},
        VirSafetyCheck::DivisorNonzero {},
    ]
    .into_iter()
    .flat_map(|check| [check.clone(), check])
    .collect::<Vec<_>>();
    assert_eq!(vc.required_checks().len(), expected.len());
    assert_eq!(observed, expected);
    let run = vc
        .document()
        .functions()
        .iter()
        .find(|function| function.function_id == CSHARP_FUNCTION)
        .expect("C# caller VC");
    let callee = vc
        .document()
        .functions()
        .iter()
        .find(|function| function.function_id == CSHARP_CALLEE_FUNCTION)
        .expect("C# callee VC");
    let members = run
        .members
        .iter()
        .map(|member| (member.id.as_str(), member))
        .collect::<BTreeMap<_, _>>();
    for audit in vc.required_checks() {
        assert_eq!(audit.function_id(), CSHARP_FUNCTION);
        assert_eq!(
            audit.evidence_route(),
            SafetyEvidenceRoute::GroupedCertificate {
                foundation: "Std.Program.Base"
            }
        );
        let member = members[audit.member_id()];
        let mut names = BTreeSet::new();
        collect_term_names(&member.conclusion, &mut names);
        assert!(
            names
                .iter()
                .any(|name| name.starts_with("Std.BitVec.BV32.")),
            "{} has no checked BV32 path: {names:?}",
            audit.member_id()
        );
        assert!(names.iter().all(|name| {
            name.starts_with("Std.BitVec.")
                || name.starts_with("Std.Bool.")
                || name == "Std.Eq"
                || name == "Std.Logic.Imp"
        }));
    }
    let run_contract = run
        .groups
        .iter()
        .find(|group| group.kind == VcGroupKind::Contract)
        .expect("C# caller contract group");
    let callee_contract = callee
        .groups
        .iter()
        .find(|group| group.kind == VcGroupKind::Contract)
        .expect("C# callee contract group");
    assert!(run_contract
        .dependencies
        .contains(&callee_contract.declaration_name));
    assert_eq!(
        skeleton.skeleton().theorem_declarations().len(),
        vc.document()
            .functions()
            .iter()
            .map(|function| function.groups.len())
            .sum::<usize>()
    );
}

