fn collect_term_names(term: &VcTerm, output: &mut BTreeSet<String>) {
    match term {
        VcTerm::Constant { name } => {
            output.insert(name.clone());
        }
        VcTerm::Apply { function, args } => {
            output.insert(function.clone());
            for argument in args {
                collect_term_names(argument, output);
            }
        }
        VcTerm::Convert { value, .. } => collect_term_names(value, output),
        VcTerm::Forall { body, .. } => collect_term_names(body, output),
        VcTerm::Var { .. } | VcTerm::Bound { .. } | VcTerm::BitVecLiteral { .. } => {}
    }
}

fn rehash_vc_value(value: &mut Value) {
    value["vc_hash"] = Value::String(ZERO_SHA256.to_owned());
    let mut payload = value.clone();
    payload
        .as_object_mut()
        .expect("VC object")
        .remove("vc_hash");
    value["vc_hash"] = Value::String(
        hash_domain_separated_raw(SUCCESSOR_VC_HASH_DOMAIN, &canonical(&payload))
            .expect("successor VC hash")
            .to_hex(),
    );
}
